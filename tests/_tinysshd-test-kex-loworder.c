/*
run the server side of the key exchange against a well-formed client public
value whose x25519 part (its last 32 bytes) is replaced by u; u = 0 keeps
the honest value
*/
static int run(const struct sshcrypto_kex *kex, const unsigned char *u) {
    unsigned char pk[sshcrypto_kem_PUBLICKEYMAX];
    unsigned char sk[crypto_kem_sntrup761x25519_SECRETKEYBYTES];
    unsigned char c[sshcrypto_kem_CIPHERTEXTMAX];
    unsigned char k[sshcrypto_kem_MAX];
    long long pklen = kex->kem_publickeybytes;

    crypto_kem_sntrup761x25519_keypair(pk, sk);
    if (u)
        byte_copy(pk + pklen - crypto_dh_x25519_BYTES, crypto_dh_x25519_BYTES,
                  u);
    return kex->enc(c, k, pk);
}

int main(void) {
    long long i, j;
    int ok = 1;

    for (i = 0; sshcrypto_kexs[i].name; ++i) {
        if (run(&sshcrypto_kexs[i], 0) != 0) ok = 0;
        for (j = 0; j < (long long) (sizeof loworder / sizeof loworder[0]);
             ++j)
            if (run(&sshcrypto_kexs[i], loworder[j]) == 0) ok = 0;
    }

    return ok ? 0 : 111;
}
